#!/usr/bin/env python3
"""Палитра игры в одном месте (ADR-0011, пункт 6; ADR-0017).

Отсюда цвета берёт генератор окружения и материалы Blender. Цвета света —
`CanvasModulate`, заливки этажей, столб шахты — живут в коде игры и
зафиксированы в ADR-0010; здесь только альбедо поверхностей.

Правило палитры сменилось в M12 (ADR-0017, решение 1). Было: «здание
приглушённое, картинку делает свет» — под серо-синее здание, где цвет служил
фоном для света. Стало: язык цвета спектрумовский и в полную силу — бирюзовые
внутренности этажей, красная кладка по бокам, жёлтые двери, синяя шахта, белые
перекрытия, — а свет ложится на него рельефом и бликом.

**Что красится палитрой раунда, здесь остаётся серым.** Стены, кладка и части
шахты рисуются в нейтральном сером: цвет им даёт `BuildingPalette` уже в игре,
и раунды отличаются друг от друга (ADR-0017, решение 2). Серый здесь — не
недоделка, а место под тон: помножь его на бирюзовый — выйдет кадр порта.
"""

from __future__ import annotations

from typing import NamedTuple

type Rgb = tuple[int, int, int]


class Material(NamedTuple):
    """Поверхность: чем светлее `specular`, тем резче блик на ней от света 2D.

    `shininess` уходит в `CanvasTexture.specular_shininess`, `specular` — в силу
    блика. Штукатурка почти не блестит, металл и стекло блестят заметно.
    """

    specular: float
    shininess: float


# --- Здание -----------------------------------------------------------------

# Внутренности этажа. Серые: тон раунда приходит из `BuildingPalette.story`,
# и на первом раунде это бирюзовый с кадра порта.
