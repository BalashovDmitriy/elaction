# --- Лифт, эскалатор --------------------------------------------------------

# Кабина в порте светло-серая, и это единственное серое пятно в кадре, которое
# не красится ничем: по ней лифт и узнаётся.
METAL: Rgb = (0xCE, 0xCE, 0xCE)
METAL_SHADE: Rgb = (0x8A, 0x8A, 0x8A)
METAL_TRIM: Rgb = (0xFF, 0xFF, 0xFF)

# --- Окна и город -----------------------------------------------------------

GLASS: Rgb = (0x9F, 0xB6, 0xC9)
