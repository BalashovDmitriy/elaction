BRICK_SHADE: Rgb = (0x86, 0x86, 0x86)
# Шов — самое светлое в кладке. Белым, как в порте, он не остаётся: тон раунда
# ложится `modulate` на весь узел стены разом (ADR-0017, решение 2), и шов
# множится вместе с кирпичом. Светлее кирпича он от этого быть не перестаёт,
# а белый шов потребовал бы второго узла на каждую боковую стену здания.
