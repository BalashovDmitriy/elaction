WALL_SHADE: Rgb = (0x9A, 0x9A, 0x9A)
WALL_TRIM: Rgb = (0xE4, 0xE4, 0xE4)

# Кладка по бокам здания. Тоже серая: её красит `BuildingPalette.masonry`,
# а кирпич даёт не цвет, а рисунок шва.
