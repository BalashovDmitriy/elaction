# --- Актёры -----------------------------------------------------------------

# Якорь оригинала: самое светлое пятно среди актёров, чтобы своего было видно
# и на погашенном этаже.
OTTO_SUIT: Rgb = (0xE8, 0xE3, 0xD2)
