# Перекрытия белые — как в порте. Тоном раунда не красятся: пол и потолок
# должны читаться одинаково в любом раунде.
SLAB_TOP: Rgb = (0xE8, 0xE8, 0xE8)
SLAB_EDGE: Rgb = (0xFF, 0xFF, 0xFF)
SLAB_FACE: Rgb = (0xC2, 0xC2, 0xC2)
SLAB_SHADOW: Rgb = (0x2A, 0x2A, 0x2A)

# --- Шахта ------------------------------------------------------------------

# Направляющие и створки. Серые под тон раунда (`BuildingPalette.shaft`),
# на первом раунде — синие, как полоса шахты в порте.
SHAFT_RAIL: Rgb = (0xBE, 0xBE, 0xBE)
SHAFT_RAIL_SHADE: Rgb = (0x8C, 0x8C, 0x8C)
SHAFT_RAIL_TRIM: Rgb = (0xEE, 0xEE, 0xEE)
# Перемычка на уровне этажа рисуется тем же светлым серым: жёлтой, как в порте,
# ей не быть — створки красит тон раунда целиком (ADR-0017, решение 3), и жёлтый
# под синим множителем стал бы грязью.

# --- Двери ------------------------------------------------------------------

# Жёлтая створка в синей раме — как в порте.
DOOR_FRAME: Rgb = (0x28, 0x38, 0xC8)
DOOR_PANEL: Rgb = (0xF0, 0xD0, 0x00)
DOOR_PANEL_SHADE: Rgb = (0xB4, 0x9A, 0x00)

# Якорь оригинала: единственное красное среди дверей.
DOOR_RED: Rgb = (0xD8, 0x20, 0x20)
DOOR_RED_SHADE: Rgb = (0x96, 0x16, 0x16)

# Коврик у двери: по нему видно, где вход, ещё до того как дверь открылась.
